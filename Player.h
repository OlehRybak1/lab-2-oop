#pragma once
#include "VideoIO.h"

/*------------------------------------------------------------
Клас Player (ПРОГРАВАЧ) містить масив об'єктів класу Video
(мультимедійна бібліотека) та методи пошуку фільмів
за акторами, назвами, темами. Керування - через текстове меню.
--------------------------------------------------------------*/
class Player
{
    int videoCount;     // кількість відеофайлів
    Video* videos;      // масив об'єктів Video
    VideoIO* ioWorker;  // об'єкт для вводу/виводу інформації про відео

    void SearchByActor();   // пошук фільмів за актором (підрядок)
    void SearchByTitle();   // пошук фільмів за назвою (підрядок)
    void SearchByTheme();   // пошук фільмів за темою (підрядок)
    void PrintMenu() const; // виводить меню на екран

public:
    Player();            // конструктор: запитує кількість і виділяє масив
    ~Player();           // деструктор: звільняє пам'ять

    void Fill();          // заповнення бібліотеки з консолі
    void ShowAll();        // вивід усіх фільмів
    void Run();            // головний цикл меню - користувач сам обирає дію
};
